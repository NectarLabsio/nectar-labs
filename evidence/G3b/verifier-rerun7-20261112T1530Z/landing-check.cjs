// G3b run 6 (i): WO-35w claims on the built landing (rendered HTML from `next start`). Usage: node landing-check.cjs <landing.html>
const fs = require("fs");
const html = fs.readFileSync(process.argv[2], "utf8");
const dec = (s) => s.replace(/&amp;/g, "&").replace(/&#x27;|&#39;|&apos;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&nbsp;|&#xa0;/g, " ");
const metas = [...html.matchAll(/<meta[^>]+(?:name|property)="(description|og:description|twitter:description)"[^>]*content="([^"]*)"/g)].map((m) => [m[1], dec(m[2])]);
let body = html.replace(/<script[\s\S]*?<\/script>/g, "").replace(/<style[\s\S]*?<\/style>/g, "").replace(/<svg[\s\S]*?<\/svg>/g, (s) => " " + (s.match(/aria-label="([^"]*)"/)?.[1] ?? "") + " ");
body = body.replace(/<\/(p|li|h[1-6]|div|summary|details|td|th|dt|dd|section|header|footer|small|figcaption)>|<br\s*\/?>/g, "\n");
const lines = dec(body.replace(/<[^>]+>/g, "")).split("\n").map((l) => l.replace(/\s+/g, " ").trim()).filter(Boolean);
const text = lines.join("\n");
const out = [];
const ok = (name, pass, detail) => out.push(`${pass ? "PASS" : "FAIL"} ${name}${detail ? ` — ${detail}` : ""}`);
ok("no 0123456789 in visible text", !text.includes("0123456789"));
ok("no 0123456789 in meta descriptions", metas.every(([, c]) => !c.includes("0123456789")), metas.map(([n, c]) => `${n}="${c.slice(0, 90)}"`).join(" | "));
out.push(`info: 0123456789 anywhere in raw HTML (incl. scripts/RSC payload): ${html.includes("0123456789")}`);
const baseLines = lines.filter((l) => /\bBase\b/.test(l));
out.push(`Base lines (${baseLines.length}):`, ...baseLines.map((l) => `  · ${l.slice(0, 220)}`));
ok("Base section says 'local fork'", baseLines.some((l) => /local fork/i.test(l)));
ok("no Base line claims a Base Sepolia deployment without 'local fork'/'not deployed'", baseLines.filter((l) => /Base Sepolia/.test(l)).every((l) => /local fork|not deployed|not on Base Sepolia/i.test(l)));
const teeLines = lines.filter((l) => /\bTEE\b/.test(l));
out.push(`TEE lines (${teeLines.length}):`, ...teeLines.map((l) => `  · ${l.slice(0, 220)}`));
ok("every TEE line says verifiable/verifiably", teeLines.length > 0 && teeLines.every((l) => /verifiab/i.test(l)));
ok("no TEE line says private/confidential", teeLines.every((l) => !/private|confidential/i.test(l)));
out.push(`info: 'confidential' anywhere in visible text: ${/confidential/i.test(text)}; 'private' lines: ${lines.filter((l) => /private/i.test(l)).map((l) => l.slice(0, 120)).join(" | ") || "none"}`);
ok("no 'until the Reserve ships'", !/until the Reserve ships/i.test(text));
const i0 = lines.findIndex((l) => /Follow one position through four states/.test(l));
const ex = i0 >= 0 ? lines.slice(i0, i0 + 60).join(" ") : "";
const pcts = [...new Set(ex.match(/\d+(?:\.\d+)?%/g) ?? [])];
out.push(`worked example found: ${i0 >= 0}; percentages in it: ${pcts.join(", ")}`);
out.push(`worked example excerpt: ${ex.slice(0, 900)}`);
ok("worked example uses LTV 40/70 and haircut 10/25 (config.yaml 4000/7000/1000/2500)", ["40%", "70%", "10%", "25%"].every((p) => pcts.includes(p)), `missing: ${["40%", "70%", "10%", "25%"].filter((p) => !pcts.includes(p)).join(",") || "none"}`);
console.log(out.join("\n"));
process.exitCode = out.some((l) => l.startsWith("FAIL")) ? 1 : 0;
